def process_telegram_command(command_text: str, chat_id: str):
    text = command_text.strip()
    cid = str(chat_id)

    if text.startswith("/start") or text.startswith("/help"):
        help_msg = (
            f"🤖 <b>ĐIỀU KHIỂN TRỢ LÝ BROKER TIKTOK LIVE & DANH MỤC</b>\n\n"
            f"📌 <b>Quản Lý Danh Mục Mã Cổ Phiếu Quan Tâm:</b>\n"
            f"🔹 <code>/watch CEO, SSI, HPG</code> : Thêm mã cổ phiếu vào Watchlist\n"
            f"🔹 <code>/watchlist</code> : Xem danh sách mã đang theo dõi\n"
            f"🔹 <code>/unwatch CEO</code> : Xóa mã khỏi danh sách\n"
            f"🔹 <code>/price</code> : Xem bảng giá thị trường realtime cho Watchlist\n"
            f"🔹 <code>/digest</code> : Xem tổng hợp phân tích AI mới nhất cho Watchlist\n\n"
            f"📌 <b>Các Lệnh Giám Sát Livestream:</b>\n"
            f"🔹 <code>/status</code> : Tổng quan trạng thái Pipeline & Workers\n"
            f"🔹 <code>/list</code> : Danh sách các kênh TikTok đang theo dõi\n"
            f"🔹 <code>/add @ten_kenh</code> : Thêm kênh TikTok mới\n"
            f"🔹 <code>/remove @ten_kenh</code> : Xóa kênh TikTok\n"
            f"🔹 <code>/report</code> : Ép trích xuất báo cáo tức thì\n"
        )
        send_message(help_msg, chat_id=cid)

    elif text.startswith("/watch") or text.startswith("/addstock"):
        parts = text.split(maxsplit=1)
        if len(parts) < 2:
            send_message("⚠️ Vui lòng nhập mã cổ phiếu! Ví dụ: <code>/watch CEO, SSI, HPG</code>", chat_id=cid)
            return

        ok, added, all_wl = add_to_watchlist(cid, parts[1])
        if ok and added:
            added_str = ", ".join([f"<b>{t}</b>" for t in added])
            all_str = ", ".join([f"<code>{t}</code>" for t in all_wl])
            msg = (
                f"✅ <b>ĐÃ THÊM MÃ CỔ PHIẾU VÀO WATCHLIST!</b>\n\n"
                f"➕ Đã thêm: {added_str}\n"
                f"📋 <b>Watchlist hiện tại ({len(all_wl)} mã):</b>\n{all_str}\n\n"
                f"🛡️ <i>Dữ liệu đã được lưu an toàn xuống Supabase DB! Mỗi 1 tiếng trong giờ giao dịch hệ thống sẽ tự báo giá cho bạn!</i>"
            )
            send_message(msg, chat_id=cid)
        else:
            send_message("⚠️ Không tìm thấy mã cổ phiếu hợp lệ!", chat_id=cid)

    elif text.startswith("/watchlist") or text.startswith("/myportfolio"):
        wl = get_user_watchlist(cid)
        if not wl:
            send_message(
                "📋 <b>DANH MỤC WATCHLIST CỦA BẠN ĐANG TRỐNG</b>\n\n💡 Hãy thêm mã quan tâm: <code>/watch CEO, SSI, HPG</code>",
                chat_id=cid,
            )
            return

        w_str = "\n".join([f"• <b>{t}</b>" for t in wl])
        msg = (
            f"📋 <b>DANH MỤC {len(wl)} MÃ CỔ PHIẾU ĐANG THEO DÕI:</b>\n\n"
            f"{w_str}\n\n"
            f"💡 Thêm: <code>/watch <mã></code> | Xóa: <code>/unwatch <mã></code>\n"
            f"📊 Gõ <code>/price</code> xem giá realtime | <code>/digest</code> xem phân tích AI!"
        )
        send_message(msg, chat_id=cid)

    elif text.startswith("/unwatch") or text.startswith("/delstock"):
        parts = text.split(maxsplit=1)
        if len(parts) < 2:
            send_message("⚠️ Vui lòng nhập mã muốn xóa! Ví dụ: <code>/unwatch CEO</code>", chat_id=cid)
            return

        ok, removed, all_wl = remove_from_watchlist(cid, parts[1])
        rem_str = ", ".join([f"<b>{t}</b>" for t in removed])
        all_str = ", ".join([f"<code>{t}</code>" for t in all_wl]) if all_wl else "<i>(Trống)</i>"
        msg = f"🗑️ <b>ĐÃ XÓA MÃ CỔ PHIẾU KHỎI WATCHLIST!</b>\n\n➖ Đã xóa: {rem_str}\n📋 Danh mục còn lại: {all_str}"
        send_message(msg, chat_id=cid)

    elif text.startswith("/price") or text.startswith("/gia") or text.startswith("/banggia"):
        wl = get_user_watchlist(cid)
        if not wl:
            send_message("📋 <b>DANH MỤC WATCHLIST CỦA BẠN ĐANG TRỐNG</b>\n\n💡 Thêm mã bằng: <code>/watch CEO, SSI, HPG</code>", chat_id=cid)
            return
        send_message("⏳ Đang lấy dữ liệu bảng giá chứng khoán realtime...", chat_id=cid)
        msg = fetch_price_digest(wl)
        send_message(msg, chat_id=cid)

    elif text.startswith("/digest") or text.startswith("/summary") or text.startswith("/baocao"):
        wl = get_user_watchlist(cid)
        if not wl:
            send_message("📋 <b>DANH MỤC WATCHLIST CỦA BẠN ĐANG TRỐNG</b>", chat_id=cid)
            return
        send_message("⏳ Đang truy vấn phân tích AI mới nhất từ Supabase DB...", chat_id=cid)
        rows = db.fetch_all(
            """
            SELECT t.text, t.analysis, t.created_at, s.handle
            FROM transcripts t
            JOIN live_sessions ls ON ls.id = t.live_session_id
            JOIN sources s ON s.id = ls.source_id
            ORDER BY t.id DESC LIMIT 10
            """
        )
        if not rows:
            send_message("📊 Chưa ghi nhận kết quả phân tích AI mới trong DB.", chat_id=cid)
            return

        matched_blocks = []
        for r in rows:
            analysis_txt = r.get("analysis") or r.get("text") or ""
            handle = r.get("handle", "@broker")
            t_str = str(r.get("created_at") or "")[:16].replace("T", " ")
            matched_blocks.append(f"📌 <b>BÁO CÁO ({handle} - <code>{t_str}</code>):</b>\n{analysis_txt[:350]}...\n")

        full_msg = (
            f"📊 <b>TỔNG HỢP PHÂN TÍCH AI (WATCHLIST)</b>\n\n"
            + "\n--------------------\n".join(matched_blocks)
            + f"\n\n🛡️ <i>Dữ liệu được xử lý bởi Whisper STT & Groq Cloud LLM (GPT-OSS-120B).</i>"
        )
        send_message(full_msg, chat_id=cid)

    elif text.startswith("/status") or text.startswith("/health"):
        counts = db.fetch_one(
            """
            SELECT
              (SELECT COUNT(*) FROM sources WHERE is_active) AS active_sources,
              (SELECT COUNT(*) FROM live_sessions WHERE status = 'CAPTURING') AS capturing,
              (SELECT COUNT(*) FROM audio_chunks WHERE status = 'PENDING') AS chunks_pending,
              (SELECT COUNT(*) FROM audio_chunks WHERE status = 'PROCESSING') AS chunks_processing,
              (SELECT COUNT(*) FROM transcripts) AS transcripts_total
            """
        )
        workers = db.fetch_all("SELECT type, status, current_task FROM workers WHERE status = 'HEALTHY'")
        w_str = "\n".join([f"• <b>{w['type']}</b>: {w.get('current_task') or 'active'}" for w in workers]) if workers else "<i>(Chưa có worker nào)</i>"

        msg = (
            f"🔴 <b>TỔNG QUAN HỆ THỐNG (SELF-BROKER PIPELINE)</b>\n\n"
            f"📋 Kênh đang theo dõi: <b>{counts.get('active_sources', 0)} kênh</b>\n"
            f"🎙️ Buổi Live đang capture: <b>{counts.get('capturing', 0)} luồng</b>\n"
            f"⏳ Audio chunks đang chờ STT: <b>{counts.get('chunks_pending', 0)} chunks</b>\n"
            f"📝 Tổng số đoạn văn bản đã bóc tách: <b>{counts.get('transcripts_total', 0)} transcripts</b>\n\n"
            f"🤖 <b>Các Worker Đang Hoạt Động:</b>\n{w_str}"
        )
        send_message(msg, chat_id=cid)

    elif text.startswith("/list") or text.startswith("/channels"):
        sources = db.fetch_all("SELECT handle, is_active FROM sources ORDER BY id")
        s_str = "\n".join([f"• <code>{s['handle']}</code> ({'Active' if s['is_active'] else 'Disabled'})" for s in sources]) if sources else "<i>(Chưa có kênh nào)</i>"
        msg = f"📋 <b>DANH SÁCH {len(sources)} KÊNH TIKTOK DỰ ÁN:</b>\n\n{s_str}"
        send_message(msg, chat_id=cid)

    elif text.startswith("/add"):
        parts = text.split(maxsplit=1)
        if len(parts) < 2:
            send_message("⚠️ Vui lòng nhập tên kênh! Ví dụ: <code>/add @ten_kenh</code>", chat_id=cid)
            return
        handle = parts[1].strip()
        if not handle.startswith("@"):
            handle = f"@{handle}"
        db.execute(
            "INSERT INTO sources (platform, handle) VALUES ('tiktok', %s) ON CONFLICT (platform, handle) DO UPDATE SET is_active = TRUE",
            (handle,),
        )
        send_message(f"✅ Đã thêm kênh TikTok: <code>{handle}</code> vào danh sách giám sát!", chat_id=cid)

    elif text.startswith("/remove") or text.startswith("/del"):
        parts = text.split(maxsplit=1)
        if len(parts) < 2:
            send_message("⚠️ Vui lòng nhập tên kênh! Ví dụ: <code>/remove @ten_kenh</code>", chat_id=cid)
            return
        handle = parts[1].strip()
        if not handle.startswith("@"):
            handle = f"@{handle}"
        db.execute("UPDATE sources SET is_active = FALSE WHERE handle = %s", (handle,))
        send_message(f"🗑️ Đã ngưng giám sát kênh TikTok: <code>{handle}</code>!", chat_id=cid)

    elif text.startswith("/report"):
        send_message("⚡ Đang ép trích xuất dữ liệu Whisper STT & Phân tích AI từ audio chunk mới nhất...", chat_id=cid)
        db.execute("SELECT * FROM recover_pipeline(1, 3, 90, 30)")
        latest = db.fetch_one(
            """
            SELECT t.text, t.analysis, s.handle
            FROM transcripts t
            JOIN live_sessions ls ON ls.id = t.live_session_id
            JOIN sources s ON s.id = ls.source_id
            ORDER BY t.id DESC LIMIT 1
            """
        )
        if latest:
            send_message(
                f"📝 <b>BÁO CÁO MỚI NHẤT ({latest['handle']}):</b>\n\n{latest.get('analysis') or latest['text']}",
                chat_id=cid,
            )
        else:
            send_message("💤 Hiện tại chưa có audio chunk mới nào hoàn tất bóc tách.", chat_id=cid)


def start_telegram_command_poller():
    bot_token = config.TELEGRAM_BOT_TOKEN
    if not bot_token:
        log.info("telegram poller disabled: TELEGRAM_BOT_TOKEN missing")
        return

    log.info("telegram command poller starting...")
    last_update_id = 0

    # Start hourly stock price notifier thread alongside command poller
    t = threading.Thread(target=hourly_stock_price_notifier_loop, daemon=True)
    t.start()

    url = f"https://api.telegram.org/bot{bot_token}/getUpdates"

    while True:
        try:
            params = {"offset": last_update_id + 1, "timeout": 20}
            res = requests.get(url, params=params, timeout=25)
            if res.status_code == 200:
                data = res.json()
                if data.get("ok"):
                    for update in data.get("result", []):
                        last_update_id = update["update_id"]
                        
                        message = update.get("message") or update.get("channel_post")
                        callback_query = update.get("callback_query")

                        if callback_query:
                            cb_data = callback_query.get("data", "")
                            chat_id = str(callback_query.get("message", {}).get("chat", {}).get("id", ""))
                            if cb_data and chat_id:
                                process_telegram_command(cb_data, chat_id)
                            continue

                        if message:
                            text = message.get("text", "")
                            chat_id = str(message.get("chat", {}).get("id", ""))
                            if text and chat_id:
                                process_telegram_command(text, chat_id)

        except Exception as e:
            log.warning("telegram poller loop exception: %s", e)

        time.sleep(2)
