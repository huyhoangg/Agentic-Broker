"""
Telegram Integration Engine:
- Message sending via Telegram Bot API
- Interactive Telegram Command Poller (/watch, /watchlist, /unwatch, /price, /digest, /status, /list, /add, /remove, /report)
- Hourly Stock Price Notifier during VN stock market trading hours
"""
import logging
import os
import threading
import time
from datetime import datetime, timedelta, timezone
import requests

from . import config, db

log = logging.getLogger("telegram")

VN_TZ = timezone(timedelta(hours=7))


def send_message(text: str, chat_id: str = None) -> bool:
    target_chat = chat_id or config.TELEGRAM_CHAT_ID
    if not config.NOTIFY_TELEGRAM or not config.TELEGRAM_BOT_TOKEN or not target_chat:
        log.info("telegram disabled or missing chat_id: %s", text[:120].replace("\n", " "))
        return False
    try:
        res = requests.post(
            f"https://api.telegram.org/bot{config.TELEGRAM_BOT_TOKEN}/sendMessage",
            json={"chat_id": target_chat, "text": text, "parse_mode": "HTML", "disable_web_page_preview": True},
            timeout=10,
        )
        if res.status_code != 200:
            log.warning("telegram error %s: %s", res.status_code, res.text[:200])
            return False
        return True
    except Exception as e:
        log.warning("telegram failed: %s", e)
        return False


# --- WATCHLIST MANAGEMENT (SUPABASE DB) ---

def init_watchlist_table():
    try:
        db.execute(
            """
            CREATE TABLE IF NOT EXISTS user_watchlist (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                chat_id TEXT NOT NULL,
                ticker TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW(),
                UNIQUE(chat_id, ticker)
            );
            """
        )
    except Exception as e:
        log.warning("init_watchlist_table note: %s", e)


def get_user_watchlist(chat_id: str) -> list:
    init_watchlist_table()
    rows = db.fetch_all("SELECT ticker FROM user_watchlist WHERE chat_id = %s ORDER BY ticker", (str(chat_id),))
    return [r["ticker"] for r in rows if "ticker" in r]


def add_to_watchlist(chat_id: str, input_str: str) -> tuple:
    init_watchlist_table()
    raw_tickers = [w.strip().upper() for w in input_str.replace(",", " ").split() if len(w.strip()) >= 2]
    if not raw_tickers:
        return False, [], []

    added = []
    for t in raw_tickers:
        if len(t) <= 6 and t.isalnum():
            db.execute(
                "INSERT INTO user_watchlist (chat_id, ticker) VALUES (%s, %s) ON CONFLICT (chat_id, ticker) DO NOTHING",
                (str(chat_id), t),
            )
            added.append(t)

    current_all = get_user_watchlist(chat_id)
    return True, added, current_all


def remove_from_watchlist(chat_id: str, input_str: str) -> tuple:
    init_watchlist_table()
    raw_tickers = [w.strip().upper() for w in input_str.replace(",", " ").split() if len(w.strip()) >= 2]
    if not raw_tickers:
        return False, [], get_user_watchlist(chat_id)

    for t in raw_tickers:
        db.execute("DELETE FROM user_watchlist WHERE chat_id = %s AND ticker = %s", (str(chat_id), t))

    current_all = get_user_watchlist(chat_id)
    return True, raw_tickers, current_all


# --- REALTIME STOCK PRICE DIGEST (VNSTOCK) ---

def fetch_price_digest(tickers: list) -> str:
    if not tickers:
        return "⚠️ Danh mục của bạn chưa có mã cổ phiếu nào."

    clean_tickers = [t.upper().strip() for t in tickers if t.strip()]
    now_str = datetime.now(VN_TZ).strftime("%H:%M %d/%m/%Y")

    try:
        import pandas as pd
        from vnstock import Trading

        t = Trading(source="vci")
        df = t.price_board(clean_tickers)
        if df is None or df.empty:
            return "⚠️ Chưa lấy được dữ liệu bảng giá chứng khoán lúc này."

        blocks = []
        for idx in range(len(df)):
            row = df.iloc[idx]

            def get_val(k1, k2=None, default=0):
                if isinstance(df.columns, pd.MultiIndex):
                    v = row.get((k1, k2))
                else:
                    v = row.get(k1) or row.get(k2)
                return v if v is not None and not pd.isna(v) else default

            tk = str(get_val("listing", "symbol", clean_tickers[min(idx, len(clean_tickers) - 1)])).upper()
            raw_match = float(get_val("match", "match_price", 0))
            raw_ref = float(get_val("match", "reference_price", get_val("listing", "ref_price", 0)))
            raw_high = float(get_val("match", "highest", 0))
            raw_low = float(get_val("match", "lowest", 0))
            raw_vol = float(get_val("match", "accumulated_volume", 0))
            raw_ceil = float(get_val("match", "ceiling_price", get_val("listing", "ceiling", 0)))
            raw_floor = float(get_val("match", "floor_price", get_val("listing", "floor", 0)))

            price = raw_match / 1000.0 if raw_match > 500 else raw_match
            ref_price = raw_ref / 1000.0 if raw_ref > 500 else raw_ref
            high = raw_high / 1000.0 if raw_high > 500 else raw_high
            low = raw_low / 1000.0 if raw_low > 500 else raw_low
            ceiling = raw_ceil / 1000.0 if raw_ceil > 500 else raw_ceil
            floor = raw_floor / 1000.0 if raw_floor > 500 else raw_floor

            change = price - ref_price if ref_price > 0 else 0.0
            change_pc = (change / ref_price * 100.0) if ref_price > 0 else 0.0

            if price >= ceiling and ceiling > 0:
                emoji = "🟣"
            elif price <= floor and floor > 0 and price > 0:
                emoji = "🔵"
            elif change > 0:
                emoji = "🟢"
            elif change < 0:
                emoji = "🔴"
            else:
                emoji = "🟡"

            sign = "+" if change > 0 else ""
            vol_str = f"{round(raw_vol / 1_000_000, 2)}M" if raw_vol >= 1_000_000 else f"{int(raw_vol):,}"

            blocks.append(
                f"{emoji} <b>{tk}</b>: <b>{price:.2f}</b> ({sign}{change:.2f} / {sign}{change_pc:.2f}%)\n"
                f"• Ref: <code>{ref_price:.2f}</code> | High: <code>{high:.2f}</code> | Low: <code>{low:.2f}</code>\n"
                f"• Khối lượng GD: <b>{vol_str} CP</b>"
            )

        return (
            f"📊 <b>BẢN TIN GIÁ CỔ PHIẾU REALTIME (WATCHLIST)</b>\n"
            f"⏰ <i>Thời điểm: {now_str} (Giờ giao dịch TTCK)</i>\n\n"
            + "\n--------------------\n".join(blocks)
            + f"\n\n🛡️ <i>Tự động cập nhật mỗi 1 tiếng trong giờ giao dịch (09:00-11:30 & 13:00-15:00).</i>"
        )
    except Exception as e:
        log.warning("fetch_price_digest error: %s", e)
        return f"⚠️ Lỗi lấy dữ liệu giá chứng khoán: {e}"


# --- HOURLY PRICE NOTIFIER LOOP ---

def is_vn_stock_market_open(dt: datetime = None) -> bool:
    if dt is None:
        dt = datetime.now(VN_TZ)
    elif dt.tzinfo is None:
        dt = dt.astimezone(VN_TZ)

    if dt.weekday() >= 5:
        return False

    tot = dt.hour * 60 + dt.minute
    in_morning = 540 <= tot <= 690  # 09:00 - 11:30
    in_afternoon = 780 <= tot <= 900  # 13:00 - 15:00
    return in_morning or in_afternoon


def hourly_stock_price_notifier_loop():
    log.info("hourly stock price notifier started")
    last_sent_hour = -1

    while True:
        try:
            now_vn = datetime.now(VN_TZ)
            curr_h = now_vn.hour

            if is_vn_stock_market_open(now_vn):
                if curr_h != last_sent_hour:
                    last_sent_hour = curr_h
                    log.info("sending hourly price updates...")
                    init_watchlist_table()
                    user_rows = db.fetch_all("SELECT DISTINCT chat_id FROM user_watchlist")
                    for u in user_rows:
                        cid = str(u["chat_id"])
                        wl = get_user_watchlist(cid)
                        if wl:
                            msg = fetch_price_digest(wl)
                            send_message(msg, chat_id=cid)
            else:
                if last_sent_hour != -1 and (curr_h < 9 or curr_h > 15 or now_vn.weekday() >= 5):
                    last_sent_hour = -1

        except Exception as e:
            log.warning("hourly_stock_price_notifier_loop error: %s", e)

        time.sleep(60)


