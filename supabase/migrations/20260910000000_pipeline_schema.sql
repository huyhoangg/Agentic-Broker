BEGIN
    IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'monitored_channels') THEN
        INSERT INTO sources (platform, handle, is_active)
        SELECT 'tiktok', channel_name, TRUE
        FROM monitored_channels
        ON CONFLICT (platform, handle) DO NOTHING;
        EXECUTE 'DROP TABLE IF EXISTS monitored_channels';
    END IF;
END $$;

